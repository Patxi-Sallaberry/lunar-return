function write_report_macros(path, m)
%WRITE_REPORT_MACROS  Emit the simulation results as LaTeX macros.
%
%   WRITE_REPORT_MACROS('docs/report/metrics.tex', metrics)
%
%   Every number quoted in the report is defined here and used as \mDVtot,
%   \mJTwoMiss and so on. The report therefore cannot drift out of step with
%   the build: change the physics, rebuild, and the PDF recompiles with the new
%   figures. Hand-typing results into a report is how a document ends up
%   claiming a value the code stopped producing three commits ago.


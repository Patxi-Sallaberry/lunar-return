    error('write_report_macros:open', 'Cannot write %s', path);
end
closer = onCleanup(@() fclose(fid));

fprintf(fid, '%% Generated by lib/util/write_report_macros.m -- do not edit.\n');
fprintf(fid, '%% Build stamp: %s\n\n', char(datetime('now','Format','yyyy-MM-dd HH:mm')));

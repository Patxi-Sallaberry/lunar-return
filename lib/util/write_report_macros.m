        val = texnum(sprintf(defs{k,3}, m.(fld)));
    else
        val = '\textbf{?}';
    end
    fprintf(fid, '\\newcommand{\\%s}{%s}\n', name, val);
end
end

% ------------------------------------------------------------------ helpers --
function s = texnum(s)
%TEXNUM  Turn C-style exponent notation into proper LaTeX.
%   sprintf('%.1e', 4.77e-8) gives "4.8e-08", which typesets inside math mode
%   as "4.8e - 08" with the exponent read as a subtraction. Every macro in this
%   file is used inside $...$, so the conversion has to happen here.
tok = regexp(s, '^([-+]?[\d.]+)[eE]([-+]?)0*(\d+)$', 'tokens', 'once');
if isempty(tok)
    return
end
mant = tok{1};
sgn  = tok{2};
expo = tok{3};
if strcmp(sgn, '+'), sgn = ''; end
% \ensuremath so the same macro works in a table cell and inside $...$ alike.
% Without it a value used outside math mode fails on \times, and wrapping the
% call sites by hand would defeat the point of generating them.
if strcmp(mant, '1')
    s = sprintf('\\ensuremath{10^{%s%s}}', sgn, expo);
else
    s = sprintf('\\ensuremath{%s\\times 10^{%s%s}}', mant, sgn, expo);
end
end
